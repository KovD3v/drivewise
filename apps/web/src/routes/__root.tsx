function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="it">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  useEffect(() => {
    if (pathname === "/contact") return;
    try { sessionStorage.setItem(CONTACT_SOURCE_KEY, pathname); } catch { /* storage unavailable */ }
  }, [pathname]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <AnimatePresence mode="wait" initial={false}>
        <motion.div
          key={pathname}
          initial={pathname === "/" ? false : { opacity: 0 }}
          animate={{ opacity: 1, transition: { duration: 0.11, ease: "easeOut" } }}
          exit={{ opacity: 0, transition: { duration: 0.07, ease: "easeIn" } }}
        >
          <Outlet />
        </motion.div>
      </AnimatePresence>
      <PageTransition />
    </QueryClientProvider>
  );
}
